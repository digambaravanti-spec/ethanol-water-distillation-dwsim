import glob
import pandas as pd
import matplotlib.pyplot as plt

DISTILLATE_FLOW = 50   # kmol/h, check this on your distillate stream

# ---- find the Excel file in the root folder, /content, or the current folder ----
files = glob.glob("/*.xlsx") + glob.glob("/content/*.xlsx") + glob.glob("*.xlsx")
print("Excel files found:", files)
d = pd.read_excel(files[0])
d.columns = d.columns.astype(str).str.strip()
print("Columns found:", list(d.columns))

def find(*keys):
    for c in d.columns:
        if all(k in c.lower() for k in keys):
            return c
    raise KeyError(f"No column containing {keys}. Columns are: {list(d.columns)}")

c_R    = find("reflux")
c_dist = find("distillate")
c_bot  = find("bottom")
c_reb  = find("reboiler")
c_con  = find("cond")

for c in d.columns:
    if c.lower() == "stages":
        d = d[d[c] == 20]

d = d.dropna(subset=[c_R]).copy()
R = d[c_R]
d["Specific energy"] = d[c_reb].abs() / (DISTILLATE_FLOW * d[c_dist]) * 3.6

plots = [
    (d[c_dist],            "Distillate ethanol mole fraction", "Distillate purity vs reflux ratio",    "tab:blue",   "distillate_etoh.png"),
    (d[c_bot],             "Bottoms ethanol mole fraction",    "Ethanol in bottoms vs reflux ratio",   "tab:orange", "bottoms_etoh.png"),
    (d[c_reb].abs(),       "Reboiler duty (kW)",               "Reboiler duty vs reflux ratio",        "tab:red",    "reboiler_duty.png"),
    (d[c_con].abs(),       "Condenser duty (kW)",              "Condenser duty vs reflux ratio",       "tab:purple", "condenser_duty.png"),
    (d["Specific energy"], "Specific energy (MJ/kmol ethanol)","Specific energy vs reflux ratio",      "tab:green",  "specific_energy.png"),
]

for y, ylabel, title, colour, fname in plots:
    fig, ax = plt.subplots(figsize=(6.5, 4.5), dpi=200)
    ax.plot(R, y, "o-", color=colour, lw=2, ms=5)
    ax.set_xlabel("Reflux ratio"); ax.set_ylabel(ylabel); ax.set_title(title)
    ax.grid(alpha=0.3)
    fig.tight_layout()
    fig.savefig(fname)
    plt.show()
    print("saved", fname)